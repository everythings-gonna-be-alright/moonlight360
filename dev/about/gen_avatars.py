#!/usr/bin/env python3
"""Makes app/src/about_images.h: the About page's two round pictures, AVATAR x AVATAR pixels each, RGBA with
anti-aliased round edges. The creator's is dev/about/creator.jpg (their GitHub picture); Claude's is drawn here, a
starburst in Claude's coral. Needs Pillow.

    python3 dev/about/gen_avatars.py"""
import math
import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(os.path.dirname(HERE)), "app", "src", "about_images.h")
AVATAR = 48
SS = 8  # drawn this many times bigger, then shrunk: smooth edges


def round_mask():
    big = Image.new("L", (AVATAR * SS, AVATAR * SS), 0)
    ImageDraw.Draw(big).ellipse((0, 0, AVATAR * SS - 1, AVATAR * SS - 1), fill=255)
    return big.resize((AVATAR, AVATAR), Image.LANCZOS)


def creator():
    im = Image.open(os.path.join(HERE, "creator.jpg")).convert("RGB")
    side = min(im.size)
    im = im.crop(((im.width - side) // 2, (im.height - side) // 2, (im.width + side) // 2, (im.height + side) // 2))
    return im.resize((AVATAR, AVATAR), Image.LANCZOS)


def claude():
    n = AVATAR * SS
    im = Image.new("RGB", (n, n), (217, 119, 87))  # coral
    d = ImageDraw.Draw(im)
    c = n / 2
    rays = 11
    cream = (250, 249, 245)
    for i in range(rays):   # rounded strokes from the middle, a little uneven
        a = 2 * math.pi * i / rays - math.pi / 2
        length = n * (0.33 if i % 2 == 0 else 0.27)
        w = int(n * 0.075)
        tip = (c + length * math.cos(a), c + length * math.sin(a))
        d.line([(c, c), tip], fill=cream, width=w)
        r = w / 2
        d.ellipse((tip[0] - r, tip[1] - r, tip[0] + r, tip[1] + r), fill=cream)
    d.ellipse((c - n * 0.09, c - n * 0.09, c + n * 0.09, c + n * 0.09), fill=cream)
    return im.resize((AVATAR, AVATAR), Image.LANCZOS)


def rgba(im):
    out = im.convert("RGBA")
    out.putalpha(round_mask())
    return out.tobytes()


def write(f, name, data):
    f.write(f"static const uint8_t {name}[ABOUT_AVATAR * ABOUT_AVATAR * 4] = {{\n")
    for i in range(0, len(data), 32):
        f.write("    " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
    f.write("};\n\n")


def main():
    with open(OUT, "w") as f:
        f.write("/* Generated by dev/about/gen_avatars.py: the About page's round pictures, RGBA. Do not edit. */\n"
                f"#pragma once\n#include <stdint.h>\n\nenum {{ ABOUT_AVATAR = {AVATAR} }};\n\n")
        write(f, "about_creator", rgba(creator()))
        write(f, "about_claude", rgba(claude()))
    big = Image.new("RGBA", (AVATAR * 2 + 8, AVATAR), (14, 14, 16, 255))
    for i, im in enumerate((creator(), claude())):
        tile = im.convert("RGBA")
        tile.putalpha(round_mask())
        big.alpha_composite(tile, (i * (AVATAR + 8), 0))
    big.resize((big.width * 4, big.height * 4), Image.NEAREST).save(os.path.join(HERE, "preview.png"))
    print(OUT)


if __name__ == "__main__":
    main()
